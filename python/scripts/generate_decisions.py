# One-time migration
# --------------------------------------------------------------------------

def split_document(doc: str, registry: dict):
    """The hand-maintained pair, decomposed into per-decision sources.

    Returns ``(preamble, entries)``. A body runs from its own ``## D-NN``
    heading to the line before the next section's block, so every authored byte
    lands in exactly one source and none lands in two. The only body bytes this
    rewrites are the first lines of D-76..D-89, which carried no heading title;
    they take the entry's existing registry title, which is already authored
    canonical prose exposed in the current index.
    """
    by_id = {entry["id"]: entry for entry in registry["decisions"]}
    lines = doc.split("\n")
    heads = [i for i, line in enumerate(lines) if SPLIT_HEADING_RE.match(line)]
    if not heads:
        raise ValueError("no decision headings found")

    def block_start(index: int) -> int:
        return index - 2 if ANCHOR_RE.match(lines[index - 2]) else index

    marker = LEGACY_BEGIN_MARK if LEGACY_BEGIN_MARK in doc else BEGIN_MARK
    preamble = doc[:doc.index(marker)]
    entries, retitled = {}, []
    for position, head in enumerate(heads):
        match = SPLIT_HEADING_RE.match(lines[head])
        decision_id = match.group(1)
        if decision_id not in by_id:
            raise ValueError(
                "{} is in the document but not the registry".format(decision_id))
        if position + 1 < len(heads):
            stop = block_start(heads[position + 1]) - 1
        else:
            stop = len(lines)
        body_lines = list(lines[head:stop])
        if match.group(2) is None:
            body_lines[0] = "## {} {} {}".format(
                decision_id, EM_DASH, by_id[decision_id]["title"])
            retitled.append(decision_id)
        body = "\n".join(body_lines).rstrip("\n") + "\n"
        entries[decision_id] = ({f: by_id[decision_id][f] for f in FIELDS}, body)
    unwritten = sorted(set(by_id) - set(entries))
    if unwritten:
        raise ValueError("registry entries with no section: {}".format(unwritten))
    return preamble, entries, retitled


def write_sources(source_dir: Path, preamble: str, entries: dict, meta: dict) -> None:
    source_dir.mkdir(parents=True, exist_ok=True)
    (source_dir / PREAMBLE_FILE).write_text(preamble, encoding="utf-8")
    (source_dir / META_FILE).write_text(
        json.dumps(meta, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for decision_id, (fields, body) in entries.items():
        path = source_dir / (decision_id + ".md")
        path.write_text(source_text(fields, body), encoding="utf-8")
        # Re-read through the real parser: a file that cannot be parsed back
        # into the registry entry it came from is a lossy migration.
        parsed, parsed_body = parse_source(path)
        if parsed != fields or parsed_body != body:
            raise ValueError("{} does not re-parse to its source entry".format(path.name))


def run_split(args) -> int:
    existing = sorted(args.source_dir.glob("D-*.md")) if args.source_dir.is_dir() else []
    if existing:
        print("decisions: refusing to split, {} already holds {} sources; the "
              "migration has already run".format(args.source_dir, len(existing)),
              file=sys.stderr)
        return 1
    registry = json.loads(args.registry.read_text(encoding="utf-8"))
    preamble, entries, retitled = split_document(
        args.doc.read_text(encoding="utf-8"), registry)
    write_sources(args.source_dir, preamble, entries,
                  {"registry_comment": registry["_comment"]})
    print("decisions: split {} sections into {} ({} headings retitled: {})".format(
        len(entries), args.source_dir, len(retitled), " ".join(retitled)))
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail when either generated output has drifted")
    parser.add_argument("--split", action="store_true",
                        help="one-time migration: build the sources from the "
                             "hand-maintained document and registry")
    parser.add_argument("--source-dir", type=Path, default=SOURCE_DIR)
    parser.add_argument("--doc", type=Path, default=DOC)
    parser.add_argument("--registry", type=Path, default=REGISTRY)
    args = parser.parse_args(argv)

    if args.split:
        return run_split(args)

    doc, registry, entries = _generate(args.source_dir)
    outputs = ((args.doc, doc), (args.registry, registry))
    if args.check:
        stale = [path.name for path, fresh in outputs
                 if path.read_text(encoding="utf-8") != fresh]
        if stale:
            print("decisions: STALE {} - run python3 python/scripts/"
                  "generate_decisions.py".format(", ".join(stale)), file=sys.stderr)
            return 1
        print("decisions: both generated outputs are up to date")
        print_notes(entries)
        return 0
    for path, fresh in outputs:
        path.write_text(fresh, encoding="utf-8")
    print("decisions: wrote {} and {}".format(args.doc.name, args.registry.name))
    print_notes(entries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
