def _is_structured_block(block) -> bool:
    """A requirement table written in the structured form.

    Either key is enough, so a half-converted table reaches the validator
    that names what it lacks, not the legacy one, which would call
    ``sources`` an unregistered code id.
    """
    return isinstance(block, dict) and ("sources" in block or "decided" in block)


def is_structured(articles) -> bool:
    """Whether a decision's ``articles`` uses the structured source form."""
    return isinstance(articles, dict) and any(
        _is_structured_block(block) for block in articles.values())


def runtime_editions() -> dict:
    """``(family, edition) -> code id`` for every registered runtime edition.

    Read through `btap.codes`, not parsed out of the code id: that
    ``necb2020`` spells a family and an edition is a convention, not a
    contract the next family has to keep.
    """
    found = {}
    for code_id in btap_codes.code_ids():
        ruleset = btap_codes.resolve(code_id)
        found[(ruleset.family, ruleset.edition)] = code_id
    return found


def _registered_list(runtime: dict) -> str:
    return ", ".join("{} {}".format(family, edition)
                     for family, edition in sorted(runtime))


def governing_code_ids(articles: dict, runtime: dict | None = None) -> list:
    """A structured decision's ``editions`` projection: the code ids its
    GOVERNING sources name, sorted.

    Incorporated and related sources never contribute. They may name a
    standard with no runtime edition at all, and a cross-reference does not
    make a decision apply anywhere.
    """
    runtime = runtime_editions() if runtime is None else runtime
    return sorted({runtime[(source["code"], source["edition"])]
                   for block in articles.values()
                   for source in block["sources"]
                   if source["role"] == ROLE_GOVERNING})


def check_structured(name: str, meta: dict) -> None:
    """The structured requirement form.

    Each requirement keeps its authored key and label -- still the
    correspondence assertion, never inferred from numbering -- adds a
    ``decided`` paraphrase, and carries one source record per code, edition
    and role. Only ``governing`` records say where the decision applies, so
    ``editions`` is DERIVED from them; an authored value is optional during
    the transition and must then equal the derivation exactly.
    """
    articles = meta["articles"]
    for reserved in (ARTICLES_UNVERIFIED, ARTICLES_NOT_APPLICABLE):
        if reserved in articles:
            raise ValueError(
                "{}: articles may not mix the legacy {!r} key with structured "
                "requirements -- a structured decision is established by its "
                "governing sources".format(name, reserved))
    legacy = sorted(key for key, block in articles.items()
                    if not _is_structured_block(block))
    if legacy:
        raise ValueError(
            "{}: articles mixes structured requirements with legacy "
            "per-edition requirement(s) {} -- convert every requirement of a "
            "decision together".format(name, legacy))

    runtime = runtime_editions()
    governed = {key: _check_requirement(name, key, block, meta, runtime)
                for key, block in sorted(articles.items())}
    # The legacy form required every claimed edition in every requirement.
    # The same holds here: a decision-wide projection that one requirement
    # does not govern would claim the decision where part of it does not
    # apply. A requirement that differs by edition splits the decision.
    if len({tuple(codes) for codes in governed.values()}) > 1:
        raise ValueError(
            "{}: requirements govern different editions {} -- every "
            "requirement of a decision governs the same code editions, so "
            "split a decision that differs by edition".format(name, governed))
    derived = governing_code_ids(articles, runtime)
    if "editions" in meta and meta["editions"] != derived:
        raise ValueError(
            "{}: editions is {!r}, but the governing sources derive {!r} -- "
            "remove the authored field or make it equal; incorporated and "
            "related sources never establish an edition".format(
                name, meta["editions"], derived))


def _check_requirement(name: str, key, block, meta: dict, runtime: dict) -> list:
    """Validate one structured requirement; return its governing code ids."""
    where = "{}: articles[{!r}]".format(name, key)
    if not isinstance(key, str) or not REQUIREMENT_KEY_RE.fullmatch(key):
        raise ValueError(
            "{} -- a structured requirement key must match {!r}, because it "
            "is the stable id generated rows link to".format(
                where, REQUIREMENT_KEY_RE.pattern))
    unexpected = sorted(set(block) - set(REQUIREMENT_FIELDS))
    if unexpected:
        raise ValueError(
            "{} has unexpected key(s) {}; a structured requirement carries "
            "only {} -- a per-edition citation list becomes a source "
            "record".format(where, unexpected, ", ".join(REQUIREMENT_FIELDS)))
    for field in ("label", "decided"):
        value = block.get(field)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(
                "{} needs a non-empty {} string".format(where, field))
    summary = meta.get("summary")
    if isinstance(summary, str) and (
            " ".join(block["decided"].split()).casefold()
            == " ".join(summary.split()).casefold()):
        raise ValueError(
            "{}: decided repeats the decision-wide summary -- state what was "
            "decided for THIS requirement".format(where))
    records = block.get("sources")
    if not isinstance(records, list) or not records:
        raise ValueError(
            "{} needs at least one [[articles.{}.sources]] record".format(
                where, key))

    identities, roles, governing = set(), {}, set()
    for position, record in enumerate(records, 1):
        here = "{} source {}".format(where, position)
        _check_source_shape(here, record, runtime)
        code, edition, role = record["code"], record["edition"], record["role"]
        if (code, edition, role) in identities:
            raise ValueError(
                "{} repeats code={!r} edition={!r} role={!r} -- one record "
                "per code, edition and role, so merge their references".format(
                    here, code, edition, role))
        identities.add((code, edition, role))
        if role == ROLE_GOVERNING:
            if (code, edition) not in runtime:
                raise ValueError(
                    "{} is governing, but {} {} is not a registered runtime "
                    "edition ({}) -- only an edition this tool runs can "
                    "establish where a decision applies; cite an external or "
                    "future source as incorporated-reference or "
                    "related".format(here, code, edition,
                                     _registered_list(runtime)))
            governing.add(runtime[(code, edition)])
        for reference in record["references"]:
            earlier = roles.setdefault((code, edition, reference), role)
            if earlier != role:
                raise ValueError(
                    "{} lists {!r} as {} after an earlier record listed it as "
                    "{} -- one provision has one role in a "
                    "requirement".format(here, reference, role, earlier))
        _check_references(here, record, runtime)
    if not governing:
        raise ValueError(
            "{} has no governing source -- incorporated and related sources "
            "never establish where a decision applies".format(where))
    return sorted(governing)


def _check_source_shape(here: str, record, runtime: dict) -> None:
    """The generic checks every source record passes, whatever its code."""
    if not isinstance(record, dict):
        raise ValueError(
            "{} must be a table with {}".format(here, ", ".join(SOURCE_FIELDS)))
    extra = sorted(set(record) - set(SOURCE_FIELDS))
    missing = [field for field in SOURCE_FIELDS if field not in record]
    if extra or missing:
        raise ValueError(
            "{}: unexpected {} / missing {}".format(here, extra, missing))
    code, edition = record["code"], record["edition"]
    if not isinstance(code, str) or not CODE_RE.fullmatch(code):
        raise ValueError(
            "{}: code {!r} is not a stable lower-case family id such as "
            "'necb' or 'ashrae-62.1'".format(here, code))
    by_code_id = {code_id: pair for pair, code_id in runtime.items()}
    if code in by_code_id:
        family, year = by_code_id[code]
        raise ValueError(
            "{}: code {!r} is a runtime code id, not a family -- write "
            "code = {!r} and edition = {!r}".format(here, code, family, year))
    if not isinstance(edition, str):
        raise ValueError(
            "{}: edition must be a quoted string, got {} {!r}".format(
                here, type(edition).__name__, edition))
    if not EDITION_RE.fullmatch(edition):
        raise ValueError(
            "{}: edition {!r} is malformed -- lower-case letters and digits, "
            "separated by '.' or '-'".format(here, edition))
    if record["role"] not in ROLES:
        raise ValueError(
            "{}: role {!r} is not one of {}".format(
                here, record["role"], ", ".join(ROLES)))
    references = record["references"]
    if not isinstance(references, list) or not references:
        raise ValueError(
            "{}: references must be a non-empty list of citations".format(here))
    seen = set()
    for reference in references:
        if not isinstance(reference, str) or not reference.strip():
            raise ValueError(
                "{}: references holds {!r}, not a non-blank string".format(
                    here, reference))
        if reference != " ".join(reference.split()):
            raise ValueError(
                "{}: reference {!r} carries stray whitespace".format(
                    here, reference))
        if reference in seen:
            raise ValueError("{} cites {!r} twice".format(here, reference))
        seen.add(reference)


def _check_references(here: str, record: dict, runtime: dict) -> None:
    """A registered edition's references must exist in its provision index; a
    registered family's other editions must use that family's canonical
    grammar; any other code is carried as authored and disclosed by
    `unvalidated_sources`."""
    code, edition = record["code"], record["edition"]
    code_id = runtime.get((code, edition))
    families = {family for family, _ in runtime}
    for reference in record["references"]:
        if code_id is not None:
            _check_provision(here, code_id, reference)
        elif code in families:
            try:
                citation = provisions.parse_citation(reference, family=code)
            except provisions.ProvisionError as exc:
                raise ValueError("{}: {}".format(here, exc)) from exc
            _check_spelling(here, reference, citation)


def _check_spelling(here: str, reference: str, citation) -> None:
    if reference != citation.canonical:
        raise ValueError(
            "{}: {!r} is not the canonical spelling -- write {!r}".format(
                here, reference, citation.canonical))


def _check_provision(here: str, code_id: str, reference: str) -> None:
    """One reference in a registered edition, against its provision index.

    Presence of the CANONICAL key is the whole test of existence and kind:
    the canonical spelling carries the kind (``Table 8.4.4.13`` is a table,
    ``8.4.4.13`` an article), so an Article cited as a Table, a missing note
    or an unqualified Division A number all fail to match.
    """
    try:
        result = provisions.check_citation(code_id, reference)
    except provisions.ProvisionError as exc:
        raise ValueError("{}: {}".format(here, exc)) from exc
    _check_spelling(here, reference, result.citation)
    status = result.status
    if status == "present":
        recorded = (result.provision or {}).get("kind")
        if recorded != result.citation.kind:
            raise ValueError(
                "{}: {} records {!r} as a {}, but the citation is a {}".format(
                    here, code_id, reference, recorded, result.citation.kind))
        return
    if status in ("absent", "not-indexed"):
        raise ValueError(
            "{}: {}{} -- a source must cite a provision its edition's index "
            "records as present".format(
                here, result.detail, _kind_hint(code_id, result.citation)))
    if status == "stale":
        raise ValueError(
            "{}: {} -- refresh the provision index before validating sources "
            "against it".format(here, result.detail))
    if status == "unsupported":
        raise ValueError(
            "{}: {} -- a registered edition's sources are validated against "
            "its provision index, and there is none".format(here, result.detail))
    raise ValueError(
        "{}: {} returned unexpected provision status {!r} for {!r}".format(
            here, code_id, status, reference))


def _kind_hint(code_id: str, citation) -> str:
    """Name a PRESENT provision the author may have meant, when the cited one
    differs only in kind or division. Advice for the refusal, never a
    substitute for it."""
    canonical = citation.canonical
    candidates = []
    if citation.kind == "table":
        candidates.append((canonical[len("Table "):],
                           "an Article and a Table are different provisions"))
    elif citation.kind == "article":
        candidates.append(("Table " + canonical,
                           "an Article and a Table are different provisions"))
    if citation.division == "B" and citation.kind in (
            "article", "sentence", "clause", "subclause"):
        candidates.append(("Division A " + canonical,
                           "an unqualified number is Division B, so a "
                           "Division A citation says so"))
    for candidate, why in candidates:
        try:
            found = provisions.check_citation(code_id, candidate)
        except provisions.ProvisionError:
            continue
        if found.status == "present" and found.citation.canonical == candidate:
            return "; {} is present ({})".format(candidate, why)
    return ""


def unvalidated_sources(entries: dict) -> list:
    """``(decision id, requirement key, code, edition, role)`` for every
    structured source no registered provision index can validate: an
    external standard, or an edition of a registered family that this
    checkout does not run. Such sources are carried as authored and never
    establish applicability; `main` names them so the gap is disclosed
    rather than silent."""
    runtime = runtime_editions()
    found = []
    for decision_id in numeric_order(entries):
        articles = entries[decision_id][0]["articles"]
        if not is_structured(articles):
            continue
        for key, block in sorted(articles.items()):
            for source in block["sources"]:
                if (source["code"], source["edition"]) not in runtime:
                    found.append((decision_id, key, source["code"],
                                  source["edition"], source["role"]))
    return found


def check_shared_requirements(entries: dict) -> None:
    """A requirement key shared by several decisions names ONE requirement,
    so its form, label and governing citations must agree wherever it
    appears.

    Each source is validated alone, so without this a shared key's
    correspondence could drift between its users -- the drift an authored key
    exists to prevent. ``decided`` and non-governing sources may differ: each
    decision states its own result and its own cross-references.
    """
    seen = {}
    for decision_id in numeric_order(entries):
        articles = entries[decision_id][0]["articles"]
        structured = is_structured(articles)
        for key, block in sorted(articles.items()):
            if key in (ARTICLES_UNVERIFIED, ARTICLES_NOT_APPLICABLE):
                continue
            if structured:
                mapping = {(source["code"], source["edition"]):
                           frozenset(source["references"])
                           for source in block["sources"]
                           if source["role"] == ROLE_GOVERNING}
            else:
                mapping = {code: frozenset(normalise_citation(value)
                                           for value in values)
                           for code, values in block.items() if code != "label"}
            current = ("structured" if structured else "legacy",
                       block["label"], mapping)
            if key not in seen:
                seen[key] = (decision_id, current)
                continue
            first, earlier = seen[key]
            if earlier[0] != current[0]:
                raise ValueError(
                    "requirement {!r} is {} in {} but {} in {} -- convert "
                    "every user of a shared key together".format(
                        key, earlier[0], first, current[0], decision_id))
            if earlier[1] != current[1]:
                raise ValueError(
                    "requirement {!r} is labelled {!r} in {} but {!r} in {} "
                    "-- one key names one requirement".format(
                        key, earlier[1], first, current[1], decision_id))
            if earlier[2] != current[2]:
                raise ValueError(
                    "requirement {!r} cites different governing provisions in "
                    "{} and {} -- one key names one requirement, so its "
                    "correspondence cannot drift between decisions".format(
                        key, first, decision_id))


def registry_entry(meta: dict) -> dict:
    """One decision's `decisions.json` entry.

    A legacy entry is its front matter in `FIELDS` order. A structured entry
    carries ``requirements`` -- one ``{id, label, decided, sources}`` per
    requirement key, in key order, with sources in authored order -- and the
    ``editions`` DERIVED from its governing sources, which validation has
    already proved equal to any authored value.
    """
    articles = meta["articles"]
    if not is_structured(articles):
        return {field: meta[field] for field in FIELDS}
    derived = {
        "editions": governing_code_ids(articles),
        "requirements": [
            {"id": key,
             "label": block["label"],
             "decided": block["decided"],
             "sources": [{field: (list(source[field])
                                  if field == "references" else source[field])
                          for field in SOURCE_FIELDS}
                         for source in block["sources"]]}
            for key, block in sorted(articles.items())],
    }
    return {field: derived[field] if field in derived else meta[field]
            for field in STRUCTURED_FIELDS}


def registered_codes() -> set:
    """The code ids that actually exist, DISCOVERED from the edition snapshots
    rather than listed, so registering a new edition does not leave this
    validation stale."""
    root = (pathlib.Path(__file__).resolve().parents[1]
            / "btap" / "codes" / "necb" / "data")
    return {p.parent.name for p in root.glob("*/manifest.json")}


def front_matter(meta: dict) -> str:
    # Emitting only the known fields would silently discard a typo'd or
    # newly-added one on any rewrite, so an unexpected key is refused here as
    # well as on the way in. A structured decision may omit `editions`, which
    # the generator derives from its governing sources.
    structured = is_structured(meta.get("articles"))
    required = set(FIELDS) - ({"editions"} if structured else set())
    extra = sorted(set(meta) - set(FIELDS))
    missing = sorted(required - set(meta))
    if extra or missing:
        raise ValueError(
            "front matter: unexpected {} / missing {}".format(extra, missing))
    lines = [FENCE]
    for field in FIELDS:
        if field == "articles" or field not in meta:
            continue            # articles is emitted as tables, after the scalars
        lines.append("{} = {}".format(field, toml_value(meta[field])))
    # `articles` becomes TOML tables, after every scalar: a table header
    # captures each key that follows it. The shape is checked here too —
    # emitting a flat list raised AttributeError deep in the writer instead of
    # saying what was wrong.
    if not isinstance(meta["articles"], dict):
        raise ValueError(
            "front matter: articles must be a map of requirement key -> "
            "table, got {}".format(type(meta["articles"]).__name__))
    for key, block in sorted(meta["articles"].items()):
        lines.append("")
        if key in (ARTICLES_UNVERIFIED, ARTICLES_NOT_APPLICABLE):
            lines.append("[articles]")
            lines.append("{} = {}".format(key, toml_value(block)))
            continue
        if _is_structured_block(block):
            lines.extend(_structured_lines(key, block))
            continue
        lines.append("[articles.{}]".format(key))
        lines.append("label = {}".format(toml_string(block["label"])))
        for code, values in sorted(
                (k, v) for k, v in block.items() if k != "label"):
            lines.append("{} = {}".format(code, toml_value(values)))
    lines.append(FENCE)
    return "\n".join(lines)


def _structured_lines(key, block: dict) -> list:
    """One structured requirement as a table plus an ARRAY OF TABLES, one
    ``[[articles.<key>.sources]]`` per record in authored order, each
    reference on its own line so a review diff shows exactly which citation
    moved. The key becomes part of a table header, so it is held to the key
    grammar before it is written, and every value goes through `toml_string`.
    """
    if not isinstance(key, str) or not REQUIREMENT_KEY_RE.fullmatch(key):
        raise ValueError(
            "front matter: requirement key {!r} must match {!r}".format(
                key, REQUIREMENT_KEY_RE.pattern))
    extra = sorted(set(block) - set(REQUIREMENT_FIELDS))
    missing = [field for field in REQUIREMENT_FIELDS if field not in block]
    if extra or missing:
        raise ValueError(
            "front matter: articles[{!r}] unexpected {} / missing {}".format(
                key, extra, missing))
    if not isinstance(block["sources"], list):
        raise ValueError(
            "front matter: articles[{!r}] sources must be a list of "
            "tables".format(key))
    lines = ["[articles.{}]".format(key),
             "label = {}".format(toml_string(block["label"])),
             "decided = {}".format(toml_string(block["decided"]))]
    for record in block["sources"]:
        if not isinstance(record, dict):
            raise ValueError(
                "front matter: articles[{!r}] has a source that is not a "
                "table".format(key))
        extra = sorted(set(record) - set(SOURCE_FIELDS))
        missing = [field for field in SOURCE_FIELDS if field not in record]
        if extra or missing:
            raise ValueError(
                "front matter: articles[{!r}] source unexpected {} / missing "
                "{}".format(key, extra, missing))
        if not isinstance(record["references"], list):
            raise TypeError(
                "not a list of references: {!r}".format(record["references"]))
        lines.extend(["", "[[articles.{}.sources]]".format(key)])
        for field in ("code", "edition", "role"):
            lines.append("{} = {}".format(field, toml_string(record[field])))
        lines.append("references = [")
        lines.extend("  {},".format(toml_string(reference))
                     for reference in record["references"])
        lines.append("]")
    return lines


def source_text(meta: dict, body: str) -> str:
    """The complete ``D-NN.md`` source file."""
    return "{}\n\n{}".format(front_matter(meta), body)


