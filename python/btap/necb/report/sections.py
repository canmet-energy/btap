def render_all(ctx):
    return "\n".join(globals()[name](ctx) for name in ORDER)


def _dig(mapping, *keys):
    """Ruby Hash#dig for nested str-keyed dicts."""
    current = mapping
    for key in keys:
        if not isinstance(current, dict):
            return None
        current = current.get(key)
        if current is None:
            return None
    return current


