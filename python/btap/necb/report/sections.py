def audit_appendix(ctx):
    rows = []
    for i, e in enumerate(ctx["audit_entries"]):
        level = str(e.get("level") or "")
        # decisions get a neutral glyph here; the checklist carries the verdict
        glyph_kind = {"warning": "warning", "info": "info"}.get(level, "na")
        rows.append(
            f'<tr id="audit-{i}"><td>{i}</td>'
            f"<td>{Html.glyph(glyph_kind)} {Html.esc(level)}</td>"
            f"<td>{Html.building_chip(e.get('building'))}</td>"
            f"<td>{Html.esc(e.get('step'))}</td><td>{Html.esc(e.get('target'))}</td>"
            f"<td>{Html.esc(e.get('action'))}</td>"
            f"<td>{Html.esc(e.get('article'))}</td>"
            f"<td>{Html.esc(compact_inputs(e))}</td></tr>")
    table = ("<table><thead><tr><th>#</th><th>Level</th><th>Applies to</th>"
             "<th>Step</th><th>Target</th><th>Action</th><th>Article</th>"
             "<th>Inputs / value</th></tr></thead><tbody>"
             + "".join(rows) + "</tbody></table>")
    return Html.section(
        "audit", "Full audit trail",
        Html.details(f"{len(ctx['audit_entries'])} audited entries (every value "
                     "used and article applied)", table))


def compact_inputs(entry):
    parts = []
    inputs = entry.get("inputs")
    if isinstance(inputs, dict) and inputs:
        parts.append(", ".join(
            f"{k}={ruby_str(ruby_round(v, 3) if isinstance(v, float) else v)}"
            for k, v in inputs.items()))
    if entry.get("value") is not None:
        parts.append(ruby_str(entry["value"]))
    return " | ".join(parts)[:220]


