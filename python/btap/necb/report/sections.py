def space_type_table(ctx, key, heading):
    types = _dig(ctx.get("proposed") or {}, "space_types")
    if not types:
        return "<p>No space types with floor area in the proposed model.</p>"

    ref_types = {t["name"]: t
                 for t in _dig(ctx.get("reference") or {}, "space_types") or []}
    rows = []
    for t in types:
        ref = ref_types.get(t["name"])
        rows.append([t["name"], Html.fmt(t["area_m2"], unit="m²"),
                     Html.fmt(t[key], prec=2),
                     Html.fmt(ref[key], prec=2) if ref else "—"])
    return (f"<h3>{Html.esc(heading)}</h3>"
            + Html.table(["Space type", "Floor area", "Proposed", "Reference"],
                         rows))


def domain_audit_notes(ctx, domain):
    """Per-domain audit table: decisions + warnings whose step matches the
    domain."""
    steps = DOMAIN_STEPS[domain]
    picked = [(e, i) for i, e in enumerate(ctx["audit_entries"])
              if any(s in str(e.get("step") or "") for s in steps)
              and e.get("level") in ("decision", "warning")]
    if not picked:
        return ""

    rows = []
    for e, i in picked[:60]:
        target = e.get("target")
        prefix = f"{target}: " if target is not None else ""
        rows.append([
            Html.raw(Html.glyph("warning" if e.get("level") == "warning"
                                else "info")),
            Html.raw(Html.building_chip(e.get("building"))),
            str(e.get("article") or ""),
            f"{prefix}{e.get('action')}",
            Html.raw(f'<a href="#audit-{i}">#{i}</a>')])
    note = (f'<p class="meta">Showing 60 of {len(picked)} — see the full audit '
            "trail.</p>" if len(picked) > 60 else "")
    return Html.details(
        f"Audited decisions for this domain ({len(picked)})",
        Html.table(["", "Applies to", "Article", "Decision", "Audit"], rows) + note)
