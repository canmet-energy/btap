# -- verdict_banner ------------------------------------------------

def verdict_banner(ctx):
    report = ctx["report"]
    badges = []
    if report.get("compliant") is not None:
        compliant = report["compliant"]
        badges.append(Html.badge(
            "PERFORMANCE PATH: PASS" if compliant else "PERFORMANCE PATH: FAIL",
            "pass" if compliant else "fail"))
    eui = report.get("eui_path")
    if eui:
        if eui.get("computed") is False:
            # the as-specified run cannot lawfully serve the 8.4.4 verdict
            # (Table 8.4.4.2 non-conformance / applicability) — say so, never
            # render a pass/fail that was not determined
            badges.append(Html.badge("EUI PATH (8.4.4): NOT COMPUTED", "warn"))
        else:
            ok = eui.get("compliant")
            badges.append(Html.badge(
                "EUI PATH (8.4.4): PASS" if ok else "EUI PATH (8.4.4): FAIL",
                "pass" if ok else "fail"))
    method = str(_dig(report, "reference", "method") or "")
    if "archetype" in method and report.get("compliant") is not None:
        compliant = report["compliant"]
        badges[0] = Html.badge(
            "EUI PATH (8.4.4): PASS" if compliant else "EUI PATH (8.4.4): FAIL",
            "pass" if compliant else "fail")
    # The performance-path tier (vs the reference building) and the EUI-path
    # tier (vs the archetype target) measure the SAME proposed energy against
    # DIFFERENT targets, so they can differ — label each by its path.
    eui_tier = _dig(report, "eui_path", "tier")
    if report.get("tier") and eui_tier:
        badges.append(Html.badge(f"PERFORMANCE TIER {report['tier']}", "tier"))
        badges.append(Html.badge(f"EUI TIER {eui_tier}", "tier"))
    elif report.get("tier"):
        badges.append(Html.badge(f"TIER {report['tier']}", "tier"))
    if _dig(report, "ghg", "level"):
        badges.append(Html.badge(f"GHG LEVEL {_dig(report, 'ghg', 'level')}", "ghg"))
    if report.get("compliant") is None:
        badges.append(Html.badge("UNDETERMINED (no annual run)", "warn"))

    proposed_kwh = _dig(report, "proposed", "total_site_kwh")
    target_kwh = (_dig(report, "reference", "total_site_kwh")
                  or _dig(report, "reference", "building_energy_target_kwh"))
    numbers = []
    if proposed_kwh is not None:
        numbers.append(
            f"Proposed: <strong>{Html.fmt(proposed_kwh, prec=0)} kWh</strong>"
            f" ({Html.fmt(_dig(report, 'proposed', 'eui_kwh_per_m2'))} kWh/m²·yr)")
    if target_kwh is not None:
        numbers.append(f"Target: <strong>{Html.fmt(target_kwh, prec=0)} kWh</strong>")
    if proposed_kwh is not None and target_kwh is not None and target_kwh > 0:
        margin = 100.0 * (target_kwh - proposed_kwh) / target_kwh
        direction = "over" if margin < 0 else "under"
        numbers.append(
            f"Margin: <strong>{ruby_round(margin, 1)}%</strong> {direction} target")

    strip = ""
    if report.get("annual") is False:
        strip = ('<p class="warnstrip">▲ SHORTENED RUN PERIOD — the results below '
                 "use the same arithmetic\n            but are NOT a code-compliant "
                 "annual determination (NECB 8.4.1.2 requires a simulated year).</p>")
    if report.get("tier") and eui_tier and report["tier"] != eui_tier:
        bet = _dig(report, "eui_path", "bet_kwh")
        strip += (
            f'<p class="meta">The performance-path tier ({report["tier"]}, vs the '
            f"reference building\n            {Html.fmt(target_kwh, prec=0)} kWh) and "
            f"the EUI-path tier ({eui_tier}, vs the archetype target\n            "
            f"{Html.fmt(bet, prec=0)} kWh) differ because the same proposed energy is "
            "measured against different\n            targets — a building declares "
            "the tier of whichever compliance path it uses.</p>")
    return ('<section id="verdict"><div class="banner">'
            '<span class="big">Compliance summary</span>\n          '
            + " ".join(badges)
            + f"<span>{' &nbsp;•&nbsp; '.join(numbers)}</span></div>{strip}</section>")


# -- path_declaration ----------------------------------------------

def path_declaration(ctx):
    report = ctx["report"]
    eui_primary = "archetype" in str(_dig(report, "reference", "method") or "")
    rows = []
    perf_used = not eui_primary and report.get("compliant") is not None
    rows.append([Html.raw("●" if perf_used else "○"),
                 "NECB 8.4.1.2 — Building Energy Performance (reference building)",
                 verdict_text(report.get("compliant") if perf_used else None)])
    eui_not_computed = _dig(report, "eui_path", "computed") is False
    eui_used = eui_primary or (report.get("eui_path") is not None
                               and not eui_not_computed)
    if eui_primary:
        eui_verdict = report.get("compliant")
    elif eui_used:
        eui_verdict = report["eui_path"].get("compliant")
    else:
        eui_verdict = None
    if eui_not_computed:
        eui_result = f"Not computed — {_dig(report, 'eui_path', 'reason')}"
    else:
        eui_result = verdict_text(eui_verdict if eui_used else None)
    rows.append([Html.raw("●" if eui_used else "○"),
                 "NECB 8.4.4 — Archetype Energy Use Intensity (2025)", eui_result])
    rows.append([Html.raw("○"), "NECB Parts 3–7 — Prescriptive/trade-off paths",
                 "Not declared by this report (see Part 5 QAQC notes in the HVAC "
                 "section if run)"])
    body = Html.table(["Used", "Compliance path", "Result"], rows)
    body += ('<p class="meta">Path declaration mirrors the City of Vancouver '
             "Building Energy Design\n          Statement structure: ● declared "
             "path(s), ○ paths not relied upon.</p>")
    return Html.section("paths", "Compliance path declaration", body)


def verdict_text(verdict):
    if verdict is True:
        return Html.raw(f"{Html.glyph('pass')} Complies")
    if verdict is False:
        return Html.raw(f"{Html.glyph('fail')} Does not comply")
    return "Not used / not determined"


# -- floor_plans ---------------------------------------------------
# Per-storey plan views from btap.modeling's plan engine (PROPOSED model; the
# reference's spaces/zones are identical by clone — stated in the section).
# ctx['floor_plans'] is the never-raise bundle {'storeys': [{'name':,
# 'svg':}], 'legend_svg':, 'empty':, 'inferred_storeys':, 'error':};
# absent/empty/error all render as a one-line note.

def floor_plans(ctx):
    plans = ctx.get("floor_plans")
    if plans is None:
        return Html.section(
            "floor-plans", "Floor plans",
            '<p class="meta">No model was available to draw floor plans from.</p>')
    if plans.get("error") or plans.get("empty") or not plans.get("storeys"):
        note = (f"floor-plan extraction failed: {Html.esc(plans['error'])}"
                if plans.get("error")
                else "the model contains no floor surfaces to draw")
        return Html.section("floor-plans", "Floor plans",
                            f'<p class="meta">{note}</p>')

    body = ('<p class="meta">Space and thermal-zone names of the PROPOSED model, '
            "one plan per\n          storey (polygons tinted per thermal zone; hover "
            "a space for its space type and area).\n          The reference "
            "building's spaces and zones are identical by construction — the "
            "reference\n          is a clone and no transform renames or "
            "rezones.</p>")
    if plans.get("inferred_storeys"):
        body += ('<p class="warnstrip">&#9650; the model carries no BuildingStory '
                 "objects — storeys\n            were INFERRED from floor elevations "
                 "(&#177;0.01 m bins).</p>")
    # zone legend deliberately not rendered (too small to read; the zone names
    # are on the plans themselves) — the bundle still carries it.
    for storey in plans["storeys"]:
        body += (f'<div class="page-break"><h3>{Html.esc(storey["name"])}</h3>'
                 f'{storey["svg"]}</div>')
    return Html.section("floor-plans", "Floor plans", body)


# -- checklist -----------------------------------------------------

def _selected_vintage_coverage_text(text, vintage):
    """Keep user-facing application detail, omitting compatibility history."""
    selected = str(vintage or "")
    text = str(text)
    if selected:
        text = text.replace("the 2020/2025 code", f"NECB {selected}")
        text = text.replace("the 2025/2020 code", f"NECB {selected}")
        text = re.sub(r"\s*\(D-57, placement: :necb2020, the default\)",
                      " (D-57)", text)
    text = re.sub(r"\s*The legacy NECB 2011 rule.*?(?=\. Gaps:|$)", "", text)
    text = text.replace(".. Gaps:", ". Gaps:")
    return text.strip()


def _checklist_statement_html(statement, *, vintage=None, coverage=False):
    """Give long coverage determinations a summary / applied / gaps hierarchy."""
    text = (_selected_vintage_coverage_text(statement, vintage)
            if coverage else str(statement))
    applied_marker = " Applied: "
    gaps_marker = " Gaps: "
    if applied_marker not in text:
        return f'<div class="checklist-statement">{Html.esc(text)}</div>'

    summary, detail = text.split(applied_marker, 1)
    applied, separator, gaps = detail.partition(gaps_marker)
    body = (f'<div class="checklist-summary">{Html.esc(summary)}</div>'
            '<div class="checklist-detail"><span>Applied</span> '
            f'{Html.esc(applied)}</div>')
    if separator:
        body += ('<div class="checklist-detail checklist-gaps"><span>Gaps</span> '
                 f'{Html.esc(gaps)}</div>')
    return f'<div class="checklist-statement">{body}</div>'


def _checklist_article(article):
    """Display the governing citation without cross-edition provenance notes."""
    return re.sub(r"\s*\(Table verified identical \d{4}/\d{4}\)\s*$", "",
                  str(article))


def checklist(ctx):
    rows = ctx["checklist_rows"]
    if not rows:
        return Html.section("checklist", "Compliance checklist",
                            "<p>No audited compliance decisions recorded.</p>")

    table_rows = []
    vintage = (ctx.get("report") or {}).get("vintage")
    for row in rows:
        determination = _checklist_statement_html(
            row.statement, vintage=vintage, coverage=row.coverage)
        if row.measured is not None:
            determination += (
                '<div class="checklist-evidence"><span>Evidence</span> '
                f'{Html.esc(row.measured)}</div>')
        table_rows.append([
            Html.raw(Html.glyph(row.glyph)),
            Html.raw(f'<a href="#audit-{row.audit_index}">'
                     f"{Html.esc(_checklist_article(row.article) if row.article else '—')}</a>"),
            Html.raw(Html.building_chip(row.building)),
            Html.raw(determination),
        ])
    body = Html.table(["", "Article", "Applies to", "Requirement / determination"],
                      table_rows, css="checklist")
    body += (
        f'<p class="meta">{Html.glyph("pass")} complies &nbsp; '
        f'{Html.glyph("fail")} does not comply &nbsp;\n          '
        f'{Html.glyph("warning")} warning / modeller attention &nbsp; '
        f'{Html.glyph("info")} scope note &nbsp;\n          '
        f'{Html.glyph("na")} informational. "Applies to" says WHICH model the row '
        f"is about —\n          {Html.building_chip('input model')} the .osm as "
        f"submitted, {Html.building_chip('proposed building')} the\n          "
        f"proposed design as run, {Html.building_chip('reference building')} the "
        f"code-generated reference,\n          {Html.building_chip(None)} a "
        "cross-building verdict. Each article links to the full audit entry.</p>")
    return Html.section("checklist", "Compliance checklist", body)


