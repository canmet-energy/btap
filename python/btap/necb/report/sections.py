def ghg(ctx):
    report = ctx["report"]
    proposed_ghg = _dig(report, "proposed", "ghg_kg_co2e")
    if proposed_ghg is None:
        return ""

    reference_ghg = _dig(report, "reference", "ghg_kg_co2e")
    body = f"<p>{Html.legend()}</p>"
    body += Charts.paired_bars(
        [["Operational GHG", proposed_ghg, reference_ghg]],
        unit="kg CO₂e/yr",
        label="Annual operational GHG emissions, proposed vs reference")
    pairs = [["Proposed emissions",
              Html.fmt(proposed_ghg, unit="kg CO₂e/yr", prec=0)]]
    if reference_ghg is not None:
        pairs.append(["Reference emissions (GHG target)",
                      Html.fmt(reference_ghg, unit="kg CO₂e/yr", prec=0)])
    level = report.get("ghg")
    if level:
        pairs.append(["Percent of GHG target",
                      Html.fmt(level.get("percent_of_ghg_target"), unit="%")])
        pairs.append(["GHG performance level (Table 11.2.1.1)",
                      Html.raw(Html.badge(f"LEVEL {level['level']}", "ghg")
                               if level.get("level")
                               else Html.badge("ABOVE TARGET — no level", "warn"))])
    body += Html.kv_table(pairs)
    body += ('<p class="meta">Operational GHG per NECB 2025 Part 11: annual energy '
             "by fuel multiplied by\n          provincial emission factors (see the "
             "audited factor values in the audit trail). Levels A–F are\n          "
             "assigned by percent of the reference building's emissions.</p>")
    return Html.section("ghg", "Operational GHG emissions (NECB 2025 Part 11)", body)


# -- envelope ------------------------------------------------------

def envelope(ctx):
    proposed = _dig(ctx.get("proposed") or {}, "envelope")
    reference = _dig(ctx.get("reference") or {}, "envelope")
    body = f"<p>{Html.legend()}</p>"
    if proposed:
        u_rows = []
        for s in proposed["surfaces"]:
            ref_match = next((r for r in (reference or {}).get("surfaces", [])
                              if r["type"] == s["type"]), None)
            if s["avg_u_w_per_m2k"] is None:
                continue
            u_rows.append([s["type"], s["avg_u_w_per_m2k"],
                           ref_match and ref_match["avg_u_w_per_m2k"]])
        chart = Charts.paired_bars(
            u_rows, unit="W/m²·K",
            label="Area-weighted average U-value by surface type", prec=3)
        body += f"<h3>Overall thermal transmittance (area-weighted)</h3>{chart}"

        area_rows = [[s["type"], Html.fmt(s["area_m2"], unit="m²"),
                      Html.fmt(s["avg_u_w_per_m2k"], prec=3)]
                     for s in proposed["surfaces"]]
        body += Html.table(["Surface type", "Exterior area", "Avg U (W/m²·K)"],
                           area_rows)
        fdwr_rows = [
            ["Fenestration-and-door-to-wall ratio (FDWR)",
             Html.fmt(proposed["fdwr"], prec=3),
             Html.fmt((reference or {}).get("fdwr"), prec=3)],
            ["Skylight-to-roof ratio (SRR)", Html.fmt(proposed["srr"], prec=3),
             Html.fmt((reference or {}).get("srr"), prec=3)]]
        body += Html.table(["Ratio", "Proposed", "Reference"], fdwr_rows)
    else:
        body += "<p>Model geometry not available to this render (report-only mode).</p>"
    body += domain_audit_notes(ctx, "envelope")
    return Html.section("envelope", "Building envelope", body, page_break=True)


# -- hvac ----------------------------------------------------------
# HVAC systems are drawn with btap.modeling's OpenStudio-App-style
# loop-diagram engine (the same one behind the system catalog). The report
# assembler computes the diagram bundles off the SDK models
# (ctx['proposed_hvac'] / ctx['reference_hvac'], plain dicts); this SDK-free
# section only lays them out. The icon <defs> they reference are embedded once
# by the assembler.

def hvac(ctx):
    body = ""
    body += hvac_building_block("Proposed building systems",
                                ctx.get("proposed_hvac"), group="p",
                                present="proposed_hvac" in ctx)
    body += hvac_building_block("Reference building systems",
                                ctx.get("reference_hvac"), group="r",
                                present="reference_hvac" in ctx, reference=True)
    body += domain_audit_notes(ctx, "hvac")
    return Html.section("hvac", "HVAC systems", body, page_break=True)


def hvac_building_block(heading, bundle, *, group, present, reference=False):
    """One labelled HVAC subsection for a building's diagram bundle. `bundle`
    is the plain dict from btap.modeling.model_hvac_diagrams (or None). A None
    bundle on the reference means there is no reference building on this path
    (e.g. the 8.4.4 archetype-EUI path); a None bundle when the key is absent
    (canned/report-only render) is stated as such."""
    out = f"<h3>{Html.esc(heading)}</h3>"
    if bundle is None:
        if not present:
            out += ('<p class="meta">Model geometry not available to this render '
                    "(report-only mode).</p>")
        elif reference:
            out += ('<p class="meta">No reference building on this path '
                    "(e.g. the 8.4.4 archetype-EUI path).</p>")
        else:
            out += '<p class="meta">Model not available to this render.</p>'
        return out

    # One entry per loop (+ a final Zone-equipment entry), each with a unique
    # id, presented as an OpenStudio-App-style <select> chooser: picking a
    # loop shows just that loop's diagram (inline JS in the assembler; on
    # print every panel is revealed). The descriptive loop labels come from
    # btap.modeling (air loops name their served zone).
    entries = [(f"{group}-{i}", loop["label"], loop["svg"])
               for i, loop in enumerate(bundle.get("loops") or [])]
    if bundle.get("zone_equipment_svg"):
        entries.append((f"{group}-z", "Zone equipment",
                        bundle["zone_equipment_svg"]))
    if not entries:
        out += ('<p class="meta">No central HVAC loops (zone-equipment-only or '
                "not modelled).</p>")
        return out
    out += hvac_loop_select(group, entries)
    return out


def hvac_loop_select(group, entries):
    """An OpenStudio-App-style per-building loop chooser: a <select> whose
    options are the building's loops (+ a Zone-equipment entry), and one
    hidden panel per entry. The first option is selected and its panel shown;
    inline JS (the assembler) swaps panels on change and reveals all on print.
    `entries` = [(id, label, svg), …]; `group` ('p'/'r') keeps the proposed
    and reference choosers independent."""
    options = "".join(
        f'<option value="{id}"{" selected" if i == 0 else ""}>'
        f"{Html.esc(label)}</option>"
        for i, (id, label, _svg) in enumerate(entries))
    panels = "".join(
        f'<div class="loop-panel" id="{id}"{"" if i == 0 else " hidden"}>'
        f'<div class="loop-panel-title">{Html.esc(label)}</div>'
        f'<div class="diagram">{svg}</div></div>'
        for i, (id, label, svg) in enumerate(entries))
    return ('<div class="hvac-select"><label class="loop-select-label">System: '
            f'<select class="loop-select">{options}</select></label>'
            f'<div class="loop-view">{panels}</div></div>')


