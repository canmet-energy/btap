def energy(ctx):
    report = ctx["report"]
    proposed = report.get("proposed") or {}
    reference = report.get("reference") or {}
    has_ref_energy = reference.get("total_site_kwh") is not None
    body = f"<p>{Html.legend()}</p>"

    end_use_rows = [
        [use.replace("_", " ").capitalize(), value,
         _dig(reference, "end_uses_kwh", use) if has_ref_energy else None]
        for use, value in (proposed.get("end_uses_kwh") or {}).items()]
    chart = Charts.paired_bars(end_use_rows, unit="kWh",
                               label="Annual end-use energy, proposed vs reference")
    if chart:
        body += f"<h3>End-use breakdown</h3>{chart}"

    totals = []
    if proposed.get("total_site_kwh") is not None:
        totals.append(["Proposed", proposed["total_site_kwh"]])
    if has_ref_energy:
        totals.append(["Reference", reference["total_site_kwh"]])
    targets = []
    if report.get("eui_path") or reference.get("building_energy_target_kwh"):
        target_value = (_dig(report, "eui_path", "bet_kwh")
                        or reference.get("building_energy_target_kwh"))
        if target_value is not None:
            targets.append(["BET (8.4.4)", target_value])
    chart2 = Charts.total_bars(totals, targets=targets)
    if chart2:
        body += f"<h3>Annual totals</h3>{chart2}"

    fuel_rows = []
    for fuel in ("electricity_kwh", "natural_gas_kwh", "district_heating_kwh",
                 "district_cooling_kwh"):
        p = proposed.get(fuel)
        r = reference.get(fuel)
        if (p is None or p == 0) and (r is None or r == 0):
            continue

        fuel_rows.append([
            fuel.replace("_kwh", "").replace("_", " ").capitalize(),
            Html.fmt(p, unit="kWh", prec=0),
            Html.fmt(r, unit="kWh", prec=0) if has_ref_energy else "—"])
    if fuel_rows:
        body += ("<h3>Energy by fuel</h3>"
                 + Html.table(["Fuel", "Proposed", "Reference"], fuel_rows))

    lines = _dig(report, "eui_path", "lines") or reference.get("lines")
    if lines:
        line_rows = [
            [line.get("archetype") or line.get("building_type"),
             Html.fmt(line.get("area_m2"), unit="m²", prec=1),
             Html.fmt(line.get("eui_kwh_per_m2"), unit="kWh/m²·yr", prec=0),
             Html.fmt(line.get("kwh") or line.get("target_kwh"), unit="kWh", prec=0)]
            for line in lines]
        body += ("<h3>Archetype-EUI building energy target (Table 8.4.4.1)</h3>"
                 + Html.table(["Archetype", "Floor area", "Target EUI",
                               "Target energy"], line_rows))

    unmet_p = proposed.get("unmet_occupied_hours")
    if unmet_p:
        unmet_r = reference.get("unmet_occupied_hours") or {}
        body += "<h3>Unmet occupied hours (limit 100 h)</h3>"
        body += Html.table(
            ["", "Proposed", "Reference"],
            [["Heating", Html.fmt(unmet_p.get("heating"), unit="h"),
              Html.fmt(unmet_r.get("heating"), unit="h")],
             ["Cooling", Html.fmt(unmet_p.get("cooling"), unit="h"),
              Html.fmt(unmet_r.get("cooling"), unit="h")]])

    iterations = report.get("capacity_iterations")
    if iterations:
        iteration_rows = []
        for i, it in enumerate(iterations, 1):
            detail = {k: v for k, v in it.items() if k != "unmet_after"}
            iteration_rows.append(
                [i, it.get("action") or it.get("adjusted") or "(see audit)",
                 Html.esc(ruby_str(detail)[:160])])
        body += Html.details(
            "Capacity auto-iteration history (8.4.1.2.(5)) — "
            f"{len(iterations)} round(s)",
            Html.table(["Round", "Adjustment", "Detail"], iteration_rows))

    return Html.section("energy", "Energy results", body, page_break=True)


