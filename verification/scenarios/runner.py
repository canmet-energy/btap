"""Execution + comparison engine for the R4 frozen scenarios (D-80 R4).

Executes the scenarios `scenario_defs.py` authors and compares the results
against the frozen baselines `manifest.json` declares. Consumed by
`python/tests/necb/test_frozen_scenarios.py` (the CI gate) and by
`freeze.py` (which adds the Ruby seal, double-run determinism, provenance,
and the atomic write).

Strictness contract (the frozen suite must never go green-but-vacuous):
- every manifest-declared baseline file must EXIST and match its sha256
  before any comparison runs;
- a CLI scenario's run dir must contain EXACTLY the declared file set —
  undeclared extras fail too;
- stream normalization substitutes the LONGEST path first and refuses to
  run if a placeholder token already occurs in the raw output;
- newlines are canonicalized (CRLF/CR -> LF) before exact comparison;
- subprocess environments are CONSTRUCTED (infrastructure allowlist +
  authored overlay), never inherited — host HBIX_* can never leak in.
"""

