# ------------------------------------------------------------ assertions

#: The complete assertion vocabulary. It is a SERIALISABLE SCHEMA — it is
#: echoed into the generated manifest.json — so no lambdas and no
#: freeze-only logic: exactly these ops, one interpreter, called from
#: freeze.py before publishing AND from `compare` on every later run. An
#: assertion that only ran at freeze time could regress silently.
ASSERT_OPS = ("json_exists", "json_equals", "json_gt", "json_in",
              "audit_entry", "path_absent", "observation_equals")

_MISSING = object()


def _dig(data, dotted):
    """Walk a dotted path; :return: the value or the _MISSING sentinel."""
    node = data
    for key in dotted.split("."):
        if isinstance(node, dict) and key in node:
            node = node[key]
        elif isinstance(node, list) and key.lstrip("-").isdigit():
            index = int(key)
            if -len(node) <= index < len(node):
                node = node[index]
            else:
                return _MISSING
        else:
            return _MISSING
    return node


def _load_json(run_dir, name, problems, label):
    path = Path(run_dir) / name
    if not path.is_file():
        problems.append(f"{label}: {name} does not exist")
        return _MISSING
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except ValueError as error:
        problems.append(f"{label}: {name} is not readable JSON ({error})")
        return _MISSING


def _subset_match(expected, actual):
    """`inputs` matches as a SUBSET, recursively: every key the assertion
    names must be present and equal; keys it does not name are free."""
    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            return False
        return all(key in actual and _subset_match(value, actual[key])
                   for key, value in expected.items())
    return expected == actual


def _audit_entries(run_dir, problems, label):
    audit = _load_json(run_dir, "audit.json", problems, label)
    if audit is _MISSING:
        return None
    return audit if isinstance(audit, list) else audit.get("entries", [])


def check_assertions(scenario, run):
    """Interpret a scenario's `asserts` block. :return: problem strings
    (empty means every assertion held). Unknown ops RAISE — a typo must
    never read as a vacuous pass."""
    problems = []
    label = scenario["id"]
    run_dir = run.run_dir
    for assertion in scenario.get("asserts", []):
        op = assertion["op"]
        if op not in ASSERT_OPS:
            raise ValueError(
                f"{label}: unknown assertion op {op!r} — the vocabulary is "
                f"{list(ASSERT_OPS)}")
        if run_dir is None and op != "observation_equals":
            problems.append(f"{label}: {op} needs a run dir and this "
                            "scenario produced none")
            continue

        if op in ("json_exists", "json_equals", "json_gt", "json_in"):
            data = _load_json(run_dir, assertion["file"], problems, label)
            if data is _MISSING:
                continue
            path = assertion["path"]
            value = _dig(data, path)
            if value is _MISSING:
                problems.append(f"{label}: {assertion['file']} has no "
                                f"{path}")
                continue
            if op == "json_exists":
                continue
            if op == "json_equals":
                if value != assertion["value"]:
                    problems.append(
                        f"{label}: {assertion['file']} {path} is "
                        f"{value!r}, expected {assertion['value']!r}")
            elif op == "json_gt":
                if not (isinstance(value, (int, float))
                        and not isinstance(value, bool)
                        and value > assertion["value"]):
                    problems.append(
                        f"{label}: {assertion['file']} {path} is "
                        f"{value!r}, expected > {assertion['value']!r}")
            elif op == "json_in":
                if value not in assertion["values"]:
                    problems.append(
                        f"{label}: {assertion['file']} {path} is "
                        f"{value!r}, expected one of "
                        f"{assertion['values']!r}")

        elif op == "audit_entry":
            entries = _audit_entries(run_dir, problems, label)
            if entries is None:
                continue
            fields = {k: v for k, v in assertion.items()
                      if k not in ("op", "count")}
            matches = [
                entry for entry in entries
                if all(_subset_match(value, entry.get(field))
                       if field == "inputs" else entry.get(field) == value
                       for field, value in fields.items())]
            if len(matches) != assertion["count"]:
                problems.append(
                    f"{label}: audit.json has {len(matches)} entries "
                    f"matching {fields!r}, expected exactly "
                    f"{assertion['count']}")

        elif op == "path_absent":
            if (Path(run_dir) / assertion["relative"]).exists():
                problems.append(f"{label}: {assertion['relative']} exists "
                                "but was asserted absent")

        elif op == "observation_equals":
            if run.observations is None:
                problems.append(
                    f"{label}: observation_equals {assertion['key']!r} but "
                    "the run carries NO observations (only API scenarios "
                    "produce them)")
                continue
            value = _dig(run.observations, assertion["key"])
            if value is _MISSING:
                problems.append(f"{label}: no observation "
                                f"{assertion['key']!r}")
            elif value != assertion["value"]:
                problems.append(
                    f"{label}: observation {assertion['key']!r} is "
                    f"{value!r}, expected {assertion['value']!r}")
    return problems


# ------------------------------------------------------------ comparison

def verify_baselines(scenario, manifest):
    """Every declared baseline exists and matches its manifest sha256."""
    problems = []
    base = BASELINES / scenario["id"]
    declared = scenario.get("baseline_sha256", {})
    if not declared and _compared_names(scenario):
        problems.append(f"{scenario['id']}: no baselines recorded in the "
                        "manifest — was this scenario ever frozen?")
    for name, digest in declared.items():
        path = base / name
        if not path.is_file():
            problems.append(f"{scenario['id']}: baseline {name} is MISSING "
                            f"({path}) — never fall back to a silent pass")
        elif sha256(path) != digest:
            problems.append(f"{scenario['id']}: baseline {name} does not "
                            "match its manifest sha256 — hand-edited?")
    if base.is_dir():
        extras = {p.name for p in base.iterdir() if p.is_file()} - set(declared)
        if extras:
            problems.append(f"{scenario['id']}: undeclared file(s) in the "
                            f"baseline dir: {sorted(extras)} — frozen "
                            "directories are exact sets, like live run dirs")
    return problems


def _compared_names(scenario):
    names = list(scenario.get("files", [])) + list(scenario.get("text_files", {}))
    for stream in ("stdout", "stderr"):
        if scenario.get("streams", {}).get(stream) == "exact":
            names.append(f"{stream}.txt")
    return names


def compare(scenario, run, spec, cr):
    problems = []
    base = BASELINES / scenario["id"]
    run_dir = Path(run.run_dir) if run.run_dir else None

    if scenario.get("expect_exit") is not None and run.exit_code != scenario["expect_exit"]:
        problems.append(f"{scenario['id']}: exit {run.exit_code}, expected "
                        f"{scenario['expect_exit']}\nstderr: {run.stderr[-800:]}")

    if scenario.get("no_run_dir"):
        if run_dir and run_dir.exists() and any(run_dir.iterdir()):
            problems.append(f"{scenario['id']}: expected NO artifacts, found "
                            f"{[p.name for p in run_dir.iterdir()]}")
    elif run_dir:
        expected = set(scenario.get("expected_run_files")
                       or (list(scenario.get("files", []))
                           + list(scenario.get("text_files", {}))))
        if expected:
            actual = {p.name for p in run_dir.iterdir() if p.is_file()}
            if actual != expected:
                problems.append(
                    f"{scenario['id']}: run dir holds {sorted(actual)}, "
                    f"declared {sorted(expected)} — extras and absences both "
                    "fail (freeze what you emit)")

    for name in scenario.get("files", []):
        diffs = []
        cr.compare_file(str(base), str(run.run_dir), name, spec, diffs)
        problems.extend(f"{scenario['id']}: {d}" for d in diffs)

    for name, mode in scenario.get("text_files", {}).items():
        baseline = (base / name).read_text(encoding="utf-8") if (base / name).is_file() else None
        live_path = Path(run.run_dir) / name
        live = live_path.read_text(encoding="utf-8") if live_path.is_file() else None
        if baseline is None or live is None:
            problems.append(f"{scenario['id']}: {name} missing on "
                            f"{'baseline' if baseline is None else 'live'} side")
            continue
        if mode == "normalized":
            baseline_n, live_n = baseline, normalize(live, run.run_dir, run.scratch)
        else:
            baseline_n, live_n = baseline, live.replace("\r\n", "\n").replace("\r", "\n")
        if baseline_n != live_n:
            problems.append(f"{scenario['id']}: {name} differs from the "
                            f"frozen baseline ({mode})")

    for stream in ("stdout", "stderr"):
        mode = scenario.get("streams", {}).get(stream)
        live = getattr(run, stream)
        if mode == "exact":
            frozen = (base / f"{stream}.txt")
            if not frozen.is_file():
                problems.append(f"{scenario['id']}: frozen {stream} missing")
                continue
            if frozen.read_text(encoding="utf-8") != normalize(live, run.run_dir or "<none>", run.scratch):
                problems.append(f"{scenario['id']}: {stream} differs from "
                                "the frozen stream")
        frags = scenario.get("fragments", {}).get(stream, {})
        for needle in frags.get("required", []):
            if needle not in live:
                problems.append(f"{scenario['id']}: {stream} lacks required "
                                f"fragment {needle!r}")
        for needle in frags.get("forbidden", []):
            if needle in live:
                problems.append(f"{scenario['id']}: {stream} contains "
                                f"forbidden fragment {needle!r}")

    frag_files = scenario.get("fragments", {})
    for name, frags in frag_files.items():
        if name in ("stdout", "stderr"):
            continue
        path = Path(run.run_dir) / name
        content = path.read_text(encoding="utf-8") if path.is_file() else ""
        for needle in frags.get("required", []):
            if needle not in content:
                problems.append(f"{scenario['id']}: {name} lacks required "
                                f"fragment {needle!r}")

    for assertion in scenario.get("byte_asserts", []):
        path = Path(run.run_dir) / assertion["file"]
        actual = path.read_text(encoding="utf-8") if path.is_file() else None
        if actual != assertion["equals"]:
            got = repr(actual)[:60]
            problems.append(f"{scenario['id']}: {assertion['file']} != "
                            f"{assertion['equals']!r} (got {got})")

    # An API worker that timed out or crashed reports it here — with
    # expect_exit possibly None, this is what keeps a dead run from
    # reading as a pass.
    if isinstance(run.observations, dict) and "error" in run.observations:
        problems.append(f"{scenario['id']}: api worker failed — "
                        f"{run.observations['error']}")

    # The authored `asserts` block, on EVERY run — the same interpreter
    # freeze.py calls before publishing, so an assertion cannot be a
    # freeze-time-only guarantee.
    problems.extend(check_assertions(scenario, run))
    return problems
